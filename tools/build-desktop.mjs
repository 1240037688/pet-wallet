#!/usr/bin/env node
/**
 * build-desktop.mjs — bundle desktop/src → desktop/plugin.js (single-file ESM).
 *
 * IMPLEMENTATION_PLAN §3.3 build strategy:
 *   --format=esm --platform=browser --bundle --target=chrome120
 *   externals (the runtime-loader whitelist): @hermes/plugin-sdk, react,
 *   react/jsx-runtime — bare imports are PRESERVED for the loader to rewrite.
 * No JSX transform needed: sources use explicit jsx() calls (ai-usage-tracker
 * style), keeping the artifact reviewable and fallback-friendly.
 *
 * Outputs:
 *   1. plugin-src/hermes-whale-widget/desktop/plugin.js   (canonical artifact)
 *   2. dist/desktop/plugin.js                              (copy for CI/acceptance)
 *
 * Fallback (no esbuild): write the artifact by hand following ai-usage-tracker's
 * 21KB single-file pattern, then run tools/check-security.mjs on it.
 */
import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SRC_ENTRY = path.join(ROOT, 'plugin-src/hermes-whale-widget/desktop/src/main.js')
const OUT_MAIN = path.join(ROOT, 'plugin-src/hermes-whale-widget/desktop/plugin.js')
const OUT_DIST = path.join(ROOT, 'dist/desktop/plugin.js')

const EXTERNALS = ['@hermes/plugin-sdk', 'react', 'react/jsx-runtime', 'react/jsx-dev-runtime']

const banner = `/*! whale-widget desktop half — GENERATED by tools/build-desktop.mjs from desktop/src — do not edit by hand */`

const result = await build({
  entryPoints: [SRC_ENTRY],
  outfile: OUT_MAIN,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['chrome120'],
  external: EXTERNALS,
  banner: { js: banner },
  minify: false,
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'info',
})

if (result.errors.length > 0) {
  console.error('build failed')
  process.exit(1)
}

fs.mkdirSync(path.dirname(OUT_DIST), { recursive: true })
fs.copyFileSync(OUT_MAIN, OUT_DIST)

const bytes = fs.statSync(OUT_MAIN).size
console.log(`artifact: ${path.relative(ROOT, OUT_MAIN)} (${bytes} bytes)`)
console.log(`copy:     ${path.relative(ROOT, OUT_DIST)}`)
